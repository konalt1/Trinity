function OgrePrecache.Apply(group, context)
	for _, path in ipairs(group.sounds or {}) do
		PrecacheResource("soundfile", path, context)
	end

	for _, path in ipairs(group.models or {}) do
		PrecacheResource("model", path, context)
	end

	for _, path in ipairs(group.particles or {}) do
		PrecacheResource("particle", path, context)
	end

	for _, unit in ipairs(group.units or {}) do
		PrecacheUnitByNameSync(unit, context)
	end
end
